//! Build script.
//!
//! Three jobs, all of which exist so a release can never silently ship the
//! wrong helper binaries:
//!
//! 1. Verify every vendored file against `vendor/SHA256SUMS` and refuse to
//!    compile if anything is missing or modified.
//! 2. Generate the asset hash table + a content id used to cache unpacked
//!    assets, and stamp the version (from FPS_MONITOR_VERSION / the git tag).
//! 3. Embed the icon and a VERSIONINFO resource when the Windows SDK's
//!    `rc.exe` is available (it is on GitHub's windows runners). A local
//!    build without the SDK still succeeds, just without exe metadata.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

include!("src/platform/sha256.rs");

/// The only external program the app needs. It is verified before compiling
/// and shipped next to the exe (or embedded in the single-file build).
const ASSETS: &[&str] = &["PresentMon.exe"];

fn main() {
    println!("cargo:rerun-if-changed=vendor/SHA256SUMS");
    println!("cargo:rerun-if-changed=assets/icon.ico");
    println!("cargo:rerun-if-env-changed=FPS_MONITOR_VERSION");
    println!("cargo:rerun-if-env-changed=GITHUB_REF_NAME");
    println!("cargo:rerun-if-env-changed=FPS_MONITOR_RC");
    println!("cargo:rerun-if-env-changed=FPS_MONITOR_WINDRES");
    for name in ASSETS {
        println!("cargo:rerun-if-changed=vendor/{name}");
    }

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let version = detect_version(&manifest_dir);
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());

    let _hashes = verify_vendor(&manifest_dir, &out_dir);
    write_version(&out_dir, &version);
    write_resource(&manifest_dir, &out_dir, &version);
}

/// The shipped version: an explicit env var (CI stamps the git tag), the ref
/// being built, the newest tag, or the Cargo version as a last resort.
fn detect_version(manifest_dir: &Path) -> String {
    let candidate = env::var("FPS_MONITOR_VERSION")
        .ok()
        .filter(|v| !v.trim().is_empty())
        .or_else(|| {
            env::var("GITHUB_REF_NAME")
                .ok()
                .filter(|v| v.starts_with('v'))
        })
        .or_else(|| {
            Command::new("git")
                .args(["describe", "--tags", "--abbrev=0"])
                .current_dir(manifest_dir)
                .output()
                .ok()
                .filter(|o| o.status.success())
                .and_then(|o| String::from_utf8(o.stdout).ok())
                .map(|s| s.trim().to_string())
                .filter(|s| !s.is_empty())
        })
        .unwrap_or_else(|| env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into()));

    candidate
        .trim()
        .trim_start_matches('v')
        .split(['-', '+'])
        .next()
        .unwrap_or("0.0.0")
        .to_string()
}

fn write_version(out_dir: &Path, version: &str) {
    let rust = format!(
        "// Generated by build.rs - do not edit.\npub const VERSION: &str = {:?};\n",
        version
    );
    fs::write(out_dir.join("version.rs"), rust).expect("write version.rs");
}

/// Verify `vendor/SHA256SUMS`, then emit the table both the embedder and the
/// runtime verifier use. Panics (build failure) rather than letting a stale or
/// tampered DLL reach an artifact.
fn verify_vendor(manifest_dir: &Path, out_dir: &Path) -> Vec<(String, String, u64)> {
    let manifest = manifest_dir.join("vendor").join("SHA256SUMS");
    let text = fs::read_to_string(&manifest).unwrap_or_else(|e| {
        panic!(
            "cannot read {}: {e}. The vendored PresentMon/sensor files are required; \
             restore them from the repository.",
            manifest.display()
        )
    });

    let mut listed: Vec<(String, String)> = Vec::new();
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let mut parts = line.split_whitespace();
        let (Some(hash), Some(name)) = (parts.next(), parts.next()) else {
            panic!("malformed line in vendor/SHA256SUMS: {line:?}");
        };
        let name = name.trim_start_matches('*');
        let hash = hash.to_ascii_lowercase();
        if hash.len() != 64 || !hash.bytes().all(|b| b.is_ascii_hexdigit()) {
            panic!("malformed SHA-256 for {name} in vendor/SHA256SUMS");
        }
        listed.push((name.to_string(), hash));
    }

    let mut result = Vec::with_capacity(ASSETS.len());
    for name in ASSETS {
        let Some((_, expected)) = listed.iter().find(|(n, _)| n == name) else {
            panic!("vendor/SHA256SUMS has no checksum for required file {name}");
        };
        let path = manifest_dir.join("vendor").join(name);
        let bytes =
            fs::read(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
        let actual = hex_digest(&bytes);
        if &actual != expected {
            panic!(
                "checksum mismatch for vendor/{name}\n  expected {expected}\n  actual   {actual}\n\
                 Re-download the file from its upstream release (see vendor/README.md) rather \
                 than working around this check."
            );
        }
        result.push((name.to_string(), actual, bytes.len() as u64));
    }

    // A content id for the whole set: the cache folder for unpacked assets.
    let mut id_input = String::new();
    for (name, hash, len) in &result {
        id_input.push_str(&format!("{name}:{hash}:{len}\n"));
    }
    let set_id = hex_digest(id_input.as_bytes());

    let mut rust = String::from("// Generated by build.rs - do not edit.\n");
    rust.push_str(&format!(
        "#[allow(dead_code)]\npub const SET_ID: &str = {:?};\n",
        &set_id[..16]
    ));
    rust.push_str("pub const FILE_HASHES: &[(&str, &str, u64)] = &[\n");
    for (name, hash, len) in &result {
        rust.push_str(&format!("    ({name:?}, {hash:?}, {len}),\n"));
    }
    rust.push_str("];\n");
    fs::write(out_dir.join("asset_hashes.rs"), rust).expect("write asset_hashes.rs");

    result
}

/// Embed icon + VERSIONINFO. Best effort: without a resource compiler the exe
/// still works, it just loses Explorer/SmartScreen metadata. Prefers the
/// Windows SDK `rc.exe` (CI), falls back to MinGW's `windres` (rustup GNU
/// toolchains on developer machines).
fn write_resource(manifest_dir: &Path, out_dir: &Path, version: &str) {
    let nums = version_numbers(version);
    let icon = manifest_dir.join("assets/icon.ico");
    let rc_path = out_dir.join("app.rc");
    let res_path = out_dir.join("app.res");
    let obj_path = out_dir.join("app.res.o");

    let icon_escaped = icon.display().to_string().replace('\\', "\\\\");
    let file_version = format!("{},{},{},{}", nums[0], nums[1], nums[2], nums[3]);
    let version_string = format!("{}.{}.{}.{}", nums[0], nums[1], nums[2], nums[3]);

    let rc = format!(
        r#"1 ICON "{icon_escaped}"

1 VERSIONINFO
FILEVERSION {file_version}
PRODUCTVERSION {file_version}
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904B0"
        BEGIN
            VALUE "CompanyName", "xuvoxuvo"
            VALUE "FileDescription", "fps-monitor - minimal FPS overlay"
            VALUE "FileVersion", "{version_string}"
            VALUE "InternalName", "fps-monitor"
            VALUE "LegalCopyright", "MIT License. Open source: github.com/xuvoxuvo/fps-monitor"
            VALUE "OriginalFilename", "fps-monitor.exe"
            VALUE "ProductName", "fps-monitor"
            VALUE "ProductVersion", "{version_string}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#
    );

    if let Err(e) = fs::write(&rc_path, rc) {
        println!("cargo:warning=could not write app.rc: {e}");
        return;
    }

    if let Some(rc_exe) = find_rc() {
        let output = Command::new(&rc_exe)
            .arg("/nologo")
            .arg("/fo")
            .arg(&res_path)
            .arg(&rc_path)
            .output();
        match output {
            Ok(o) if o.status.success() => {
                println!("cargo:rustc-link-arg={}", res_path.display());
            }
            Ok(o) => println!(
                "cargo:warning=rc.exe failed (exit {}): {}",
                o.status,
                String::from_utf8_lossy(&o.stderr).trim()
            ),
            Err(e) => println!("cargo:warning=could not run {}: {e}", rc_exe.display()),
        }
        return;
    }

    if let Some(windres) = find_windres() {
        let output = Command::new(&windres)
            .arg("-O")
            .arg("coff")
            .arg("-i")
            .arg(&rc_path)
            .arg("-o")
            .arg(&obj_path)
            .output();
        match output {
            Ok(o) if o.status.success() => {
                println!("cargo:rustc-link-arg={}", obj_path.display());
            }
            Ok(o) => println!(
                "cargo:warning=windres failed (exit {}): {}",
                o.status,
                String::from_utf8_lossy(&o.stderr).trim()
            ),
            Err(e) => println!("cargo:warning=could not run {}: {e}", windres.display()),
        }
        return;
    }

    println!(
        "cargo:warning=neither rc.exe (Windows SDK) nor windres (MinGW) was found - building \
         without the exe icon and version metadata"
    );
}

fn version_numbers(version: &str) -> [u32; 4] {
    let mut out = [0u32; 4];
    for (i, part) in version.split('.').take(4).enumerate() {
        let digits: String = part.chars().take_while(|c| c.is_ascii_digit()).collect();
        out[i] = digits.parse().unwrap_or(0);
    }
    out
}

/// `rc.exe` ships with the Windows SDK (installed on GitHub's windows-latest
/// images). Also honour an explicit `FPS_MONITOR_RC`.
fn find_rc() -> Option<PathBuf> {
    if let Ok(explicit) = env::var("FPS_MONITOR_RC") {
        let p = PathBuf::from(explicit);
        if p.is_file() {
            return Some(p);
        }
    }

    let mut roots: Vec<PathBuf> = Vec::new();
    for var in ["ProgramFiles(x86)", "ProgramFiles"] {
        if let Ok(pf) = env::var(var) {
            roots.push(
                PathBuf::from(pf)
                    .join("Windows Kits")
                    .join("10")
                    .join("bin"),
            );
        }
    }

    let mut versions: Vec<PathBuf> = Vec::new();
    for root in roots {
        if let Ok(entries) = fs::read_dir(&root) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.is_dir() {
                    let candidate = path.join("x64").join("rc.exe");
                    if candidate.is_file() {
                        versions.push(candidate);
                    }
                }
            }
        }
        // Older SDK layouts put rc.exe directly under bin\x64.
        let legacy = root.join("x64").join("rc.exe");
        if legacy.is_file() {
            versions.push(legacy);
        }
    }

    versions.sort();
    versions.pop()
}

/// MinGW's resource compiler, for rustup's GNU toolchain on a machine without
/// the Windows SDK. Also honour an explicit `FPS_MONITOR_WINDRES`.
fn find_windres() -> Option<PathBuf> {
    if let Ok(explicit) = env::var("FPS_MONITOR_WINDRES") {
        let p = PathBuf::from(explicit);
        if p.is_file() {
            return Some(p);
        }
    }
    let path = env::var_os("PATH")?;
    env::split_paths(&path)
        .map(|dir| dir.join("windres.exe"))
        .find(|candidate| candidate.is_file())
}
