//! Where PresentMon comes from.
//!
//! Two supported layouts:
//!
//! * **sidecar** (default): `<exe dir>\bin\PresentMon.exe` - used by the zip
//!   release and by `cargo run` (which falls back to the checkout's `vendor\`).
//! * **embedded** (`--features embed-assets`): the same bytes are compiled into
//!   the exe and unpacked once into
//!   `%LOCALAPPDATA%\fps-monitor\runtime\<content-id>\`, then hash-verified.
//!
//! Everything is addressed by absolute path, and PresentMon is spawned with
//! that directory as its working directory.

use crate::platform::sha256;
use std::fs;
#[cfg(feature = "embed-assets")]
use std::io::Write;
use std::path::{Path, PathBuf};

// Generated by build.rs from vendor/SHA256SUMS.
include!(concat!(env!("OUT_DIR"), "/asset_hashes.rs"));

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[allow(dead_code)] // `Embedded` only exists in --features embed-assets builds
pub enum Mode {
    /// Files sit in `bin\` next to the exe (release zip).
    Sidecar,
    /// Files were compiled in and unpacked to LOCALAPPDATA.
    Embedded,
    /// Development run: `vendor\` in the crate checkout.
    Vendor,
    /// Nothing usable found; the overlay degrades, with status messages.
    Missing,
}

pub struct Assets {
    pub dir: PathBuf,
    pub mode: Mode,
    pub note: String,
}

impl Assets {
    pub fn locate() -> Self {
        #[cfg(feature = "embed-assets")]
        {
            match extract_embedded() {
                Ok(dir) => Self {
                    dir,
                    mode: Mode::Embedded,
                    note: "embedded in the exe, unpacked to LOCALAPPDATA".into(),
                },
                Err(e) => {
                    let mut assets = Self::locate_sidecar();
                    assets.note = format!("embedded unpack failed ({e}); {}", assets.note);
                    assets
                }
            }
        }

        #[cfg(not(feature = "embed-assets"))]
        {
            Self::locate_sidecar()
        }
    }

    fn locate_sidecar() -> Self {
        let exe_dir = std::env::current_exe()
            .ok()
            .and_then(|p| p.parent().map(Path::to_path_buf))
            .unwrap_or_else(|| PathBuf::from("."));

        let sidecar = exe_dir.join("bin");
        if looks_like_assets(&sidecar) {
            return Self {
                dir: sidecar,
                mode: Mode::Sidecar,
                note: "sidecar bin\\ folder".into(),
            };
        }
        if looks_like_assets(&exe_dir) {
            return Self {
                dir: exe_dir,
                mode: Mode::Sidecar,
                note: "next to the exe".into(),
            };
        }
        if let Some(manifest_dir) = option_env!("CARGO_MANIFEST_DIR") {
            let vendor = PathBuf::from(manifest_dir).join("vendor");
            if looks_like_assets(&vendor) {
                return Self {
                    dir: vendor,
                    mode: Mode::Vendor,
                    note: "developer checkout (vendor\\)".into(),
                };
            }
        }
        Self {
            dir: sidecar,
            mode: Mode::Missing,
            note: "no bin\\ folder found next to the exe".into(),
        }
    }

    pub fn path(&self, name: &str) -> PathBuf {
        self.dir.join(name)
    }

    pub fn has(&self, name: &str) -> bool {
        self.path(name).is_file()
    }

    pub fn missing(&self) -> Vec<&'static str> {
        FILE_HASHES
            .iter()
            .filter(|(name, _, _)| !self.has(name))
            .map(|(name, _, _)| *name)
            .collect()
    }

    /// Check sizes and SHA-256 for every file. Used by `--check` and right
    /// after unpacking; never on the normal startup path.
    pub fn verify(&self) -> Result<(), Vec<String>> {
        let mut problems = Vec::new();
        for (name, expected_hash, expected_len) in FILE_HASHES {
            let path = self.path(name);
            let bytes = match fs::read(&path) {
                Ok(bytes) => bytes,
                Err(e) => {
                    problems.push(format!("{}: cannot read ({e})", path.display()));
                    continue;
                }
            };
            if bytes.len() as u64 != *expected_len {
                problems.push(format!(
                    "{}: size {} != expected {}",
                    path.display(),
                    bytes.len(),
                    expected_len
                ));
                continue;
            }
            let actual = sha256::hex_digest(&bytes);
            if &actual != expected_hash {
                problems.push(format!(
                    "{}: checksum mismatch (expected {expected_hash}, got {actual})",
                    path.display()
                ));
            }
        }
        if problems.is_empty() {
            Ok(())
        } else {
            Err(problems)
        }
    }

    pub fn describe(&self) -> String {
        format!("{:?} - {} ({})", self.mode, self.dir.display(), self.note)
    }
}

fn looks_like_assets(dir: &Path) -> bool {
    dir.join("PresentMon.exe").is_file()
}

#[cfg(feature = "embed-assets")]
static EMBEDDED: &[(&str, &[u8])] = &[(
    "PresentMon.exe",
    include_bytes!("../../vendor/PresentMon.exe"),
)];

#[cfg(feature = "embed-assets")]
fn extract_embedded() -> Result<PathBuf, String> {
    let base = runtime_cache_dir();
    let dir = base.join(SET_ID);
    let marker = dir.join(".verified");

    if marker.is_file() && EMBEDDED.iter().all(|(name, _)| dir.join(name).is_file()) {
        // Hash-check the cache before trusting it: a truncated write or an
        // over-eager "cleaner" must not turn into a mysterious .NET failure.
        let cached = Assets {
            dir: dir.clone(),
            mode: Mode::Embedded,
            note: String::new(),
        };
        if cached.verify().is_ok() {
            return Ok(dir);
        }
    }

    fs::create_dir_all(&dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    let _ = fs::remove_file(&marker);

    for (name, bytes) in EMBEDDED {
        let target = dir.join(name);
        let up_to_date = fs::read(&target)
            .map(|existing| {
                existing.len() == bytes.len()
                    && sha256::hex_digest(&existing) == sha256::hex_digest(bytes)
            })
            .unwrap_or(false);
        if up_to_date {
            continue;
        }

        // Write-then-rename: a half-written DLL would be far worse than a
        // failed start, and an antivirus scanner holding the old file open
        // must not corrupt the new one.
        let tmp = dir.join(format!(".{name}.{}.tmp", std::process::id()));
        {
            let mut file =
                fs::File::create(&tmp).map_err(|e| format!("create {}: {e}", tmp.display()))?;
            file.write_all(bytes)
                .map_err(|e| format!("write {}: {e}", tmp.display()))?;
            file.sync_all().ok();
        }
        if fs::rename(&tmp, &target).is_err() {
            let _ = fs::remove_file(&target);
            fs::rename(&tmp, &target)
                .map_err(|e| format!("rename to {}: {e}", target.display()))?;
        }
    }

    let assets = Assets {
        dir: dir.clone(),
        mode: Mode::Embedded,
        note: String::new(),
    };
    if let Err(problems) = assets.verify() {
        return Err(format!(
            "unpacked files failed verification: {}",
            problems.join("; ")
        ));
    }
    let _ = fs::File::create(&marker);
    Ok(dir)
}

#[cfg(feature = "embed-assets")]
fn runtime_cache_dir() -> PathBuf {
    let base = std::env::var_os("LOCALAPPDATA")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("APPDATA").map(PathBuf::from))
        .unwrap_or_else(std::env::temp_dir);
    base.join(crate::app::config::APP_NAME).join("runtime")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_manifest_is_complete() {
        assert_eq!(FILE_HASHES.len(), 1);
        assert_eq!(SET_ID.len(), 16);
        for (name, hash, len) in FILE_HASHES {
            assert!(!name.is_empty());
            assert_eq!(hash.len(), 64);
            assert!(*len > 0);
        }
    }
}
